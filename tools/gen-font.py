"""Regenerates libs/fb-console/src/font.rs from an 8x16 PSF1 font (Terminus)
with a Unicode table: the glyphs of printable ASCII, of Latin-1 (U+00A0 to
U+00FF) and of the euro sign, by cell code (ADR 0076): a code is the
character's Latin-1 value, the euro sign is 0x80 (a C1 control, never shown)
and every other code shows the glyph of `?`."""
import gzip
import struct
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-Terminus16.psf.gz"
d = gzip.open(src).read()
assert d[:2] == b"\x36\x04" and d[3] == 16, "expected a PSF1 font with 16-row glyphs"
assert d[2] & 2, "expected a PSF1 font with a Unicode table"
count = 512 if d[2] & 1 else 256
glyphs = d[4:4 + count * 16]

# Unicode table: per glyph, its code points, then 0xFFFF; 0xFFFE starts a
# sequence (combining forms), skipped.
index = {}
table = d[4 + count * 16:]
pos, glyph = 0, 0
while glyph < count and pos + 1 < len(table):
    (v,) = struct.unpack_from("<H", table, pos)
    pos += 2
    if v == 0xFFFF:
        glyph += 1
    elif v == 0xFFFE:
        while struct.unpack_from("<H", table, pos)[0] != 0xFFFF:
            pos += 2
    else:
        index.setdefault(v, glyph)

EURO = 0x80
shown = {c: c for c in list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))}
shown[EURO] = 0x20AC
missing = [hex(u) for u in shown.values() if u not in index]
assert not missing, f"the font lacks {missing}"

# The glyphs stay under the font's licence (OFL-1.1), not the project's.
lines = ["// SPDX-FileCopyrightText: 2010 Dimitar Toshkov Zhekov\n",
         "// SPDX-License-Identifier: OFL-1.1\n",
         "//! 8x16 console font: printable ASCII, Latin-1 and the euro sign, by\n",
         "//! cell code (`crate::cell_code`, ADR 0076).\n//!\n",
         "//! Extracted from `Lat15-Terminus16.psf` (Terminus Font, (c) 2010 Dimitar Toshkov\n",
         "//! Zhekov), SIL Open Font License 1.1: see `FONT-LICENSE-OFL.txt`.\n",
         "//! Generated by `tools/gen-font.py`; do not edit by hand.\n\n",
         "pub const GLYPH_WIDTH: usize = 8;\npub const GLYPH_HEIGHT: usize = 16;\n\n",
         "/// The cell code of the euro sign.\n",
         "pub const EURO: u8 = 0x%02X;\n\n" % EURO,
         "/// One glyph per cell code, one row per byte, bit 7 = leftmost pixel;\n",
         "/// codes that show no character have the glyph of `?`.\n",
         "pub static GLYPHS: [[u8; GLYPH_HEIGHT]; 256] = [\n"]
for code in range(256):
    u = shown.get(code, ord("?"))
    g = index[u]
    rows = ", ".join("0x%02X" % b for b in glyphs[g * 16:(g + 1) * 16])
    if code not in shown:
        name = "(not shown)"
    elif u == 0x20:
        name = "space"
    elif u == 0x5C:
        name = "backslash"
    elif u == 0xA0:
        name = "no-break space"
    elif u == 0xAD:
        name = "soft hyphen"
    else:
        name = chr(u)
    lines.append("    [%s], // %02X %s\n" % (rows, code, name))
lines.append("];\n")
open("libs/fb-console/src/font.rs", "w", encoding="utf-8").write("".join(lines))
